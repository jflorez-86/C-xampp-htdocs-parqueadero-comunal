
USE parqueadero_comunal;

-- Rol administrativo.
ALTER TABLE administradores
ADD COLUMN rol ENUM('superadmin', 'admin')
NOT NULL DEFAULT 'admin';

-- Evitar que un residente ocupe varios puestos simultáneamente.
ALTER TABLE puestos
ADD UNIQUE KEY uq_puesto_residente (residente_id);

-- Facilitar las consultas por placa y por fecha.
CREATE INDEX idx_residente_nombre
ON residentes(nombres);

CREATE INDEX idx_movimientos_residente_fecha
ON movimientos(residente_id, fecha_hora);

-- Registrar el estado de cada movimiento.
ALTER TABLE movimientos
ADD COLUMN registrado_en TIMESTAMP
NOT NULL DEFAULT CURRENT_TIMESTAMP;

